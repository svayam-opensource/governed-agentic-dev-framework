/**
 * SKILLS FROM RULE ROWS (intent 03 spec §5, D6; ruling X12; task L14).
 *
 * The resident tier (C01) rides in every agent file on every turn. Everything else an agent must or should do is
 * needed only when it is doing that thing — so it is delivered as a SKILL: a short description the agent always
 * sees, and a body it loads when the work matches. This replaces the per-event `onDemandCues` nobody called (W7).
 *
 *   UNIT     one skill per SOURCE-DOCUMENT SECTION holding in-force C02 or C03 rows that bind an agent (X12).
 *   NAME     `gov-<doc-slug>-<section-slug>`, the section slug being its number and title — so renaming a section
 *            renames its skill, and the build deletes the old one (staleSkillDirs). ≤ 64 chars, [a-z0-9-].
 *   FRONT    `name`, `description` (lead + section title + "Use when …" from the rows' bindings), `gov-ids`,
 *            `policy-version` (the newest `start.version` among the section's rows: the version at which this
 *            text took its present form — an unrelated policy bump does not churn every skill).
 *   BODY     each rule in rule order (framework then org, each by id number): its GOV id, Required (C02) or
 *            Preferred (C03), and its cue — or, for a row with no cue, the expectation the owner approved. Then a
 *            link to the source section and "generated by gov — do not edit".
 *
 * WHY A ROW WITHOUT A CUE STILL COUNTS. X12 groups by section "that has C02 or C03 agent rows"; it does not ask for
 * a cue. The approved expectation is the rule's own words, so it is what the agent reads when nobody wrote a shorter
 * cue. Every on-demand row in the shipped framework store today is cue-less; requiring a cue would ship no skills.
 *
 * Pure and byte-stable: rows and document text in, files out — no disk, no clock. `gov rules check` compares bytes.
 */
import * as path from "node:path";
import type { RuleRow } from "../rules/model/rule-row.js";
import { compareVersions } from "../rules/model/rule-row.js";
import type { RuleSet } from "../rules/model/contracts.js";
import { policySections } from "../rules/checks/sections.js";
import { bindingGlobs, onDemandRows } from "../rules/cues/on-demand.js";
import { SKILL_MARK, SKILL_GENERATED, SKILL_PREFIX, SKILL_TARGETS } from "./locations.js";

export { SKILL_TARGETS, SKILL_GENERATED, SKILL_MARK, isGovSkill, staleSkillDirs, isGovSkillPath } from "./locations.js";

/** The agents' limits (verified 2026-10-12, see locations.ts). */
export const SKILL_NAME_MAX = 64;
export const SKILL_DESCRIPTION_MAX = 1024;

/** Reads a policy document by its repository-relative path; null = not there. */
export type ReadDoc = (doc: string) => string | null;

export interface Skill {
  readonly name: string;
  readonly doc: string;
  readonly section: string;
  /** The section heading's title, without its number; null when the document could not be read. */
  readonly title: string | null;
  /** The rows' GOV ids, in rule order. */
  readonly ids: readonly string[];
  /** The whole SKILL.md. */
  readonly content: string;
}

/** Lowercase, apostrophes dropped, every other run of non-alphanumerics one hyphen, none at the ends. */
const slug = (s: string): string =>
  s.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

/** GitHub's heading anchor: lowercase, punctuation dropped (hyphens kept), spaces to hyphens. */
const anchor = (heading: string): string =>
  heading.trim().toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, "").replace(/\s/g, "-");

/** The heading text of a numbered section (`### 6.5 Saying which model it runs` → that line minus the hashes). */
function headingOf(docText: string | null, section: string): string | null {
  if (docText === null) return null;
  const s = policySections(docText).find((x) => x.section === section);
  const first = s?.text.split(/\r?\n/).find((l) => /^\s{0,3}#{1,6}\s/.test(l));
  return first ? first.replace(/^\s{0,3}#{1,6}\s+/, "").trim() : null;
}

/** The title alone: the heading without its number (`6.5 Saying…` → `Saying…`). */
const titleOf = (heading: string | null): string | null => {
  if (heading === null) return null;
  const t = heading.replace(/^\d+(?:\.\d+)*\.?\s*/, "").trim();
  return t || null;
};

/** `gov-<doc>-<number>-<title>`, the title cut at a hyphen to fit. */
function nameOf(doc: string, section: string, title: string | null): string {
  const head = `${SKILL_PREFIX}${slug(path.posix.basename(doc).replace(/\.[^.]+$/, ""))}-${slug(section) || "preamble"}`;
  let name = head;
  if (title && slug(title)) {
    const room = SKILL_NAME_MAX - head.length - 1;
    let t = slug(title);
    if (t.length > room) t = t.slice(0, room + 1).replace(/-[^-]*$/, "") || t.slice(0, Math.max(room, 0));
    t = t.replace(/-+$/, "");
    if (t) name = `${head}-${t}`;
  }
  return name.slice(0, SKILL_NAME_MAX).replace(/-+$/, "");
}

/** The rule's line: its id, how strongly it binds, and what the agent reads — the cue, else the expectation. */
const strength = (r: RuleRow): string => r.level === "C02"
  ? "Required (C02 — only an approved exception waives it)"
  : "Preferred (C03 — deviate only with a recorded reason)";
const ruleLine = (r: RuleRow): string => `- **${r.id}** · ${strength(r)} · ${(r.cue?.text ?? r.expectation).trim()}`;

/** "Use when …" clauses, from each row's bindings; a row with none says what it expects instead. Deduplicated. */
function useWhen(rows: readonly RuleRow[]): string[] {
  const out: string[] = [];
  const add = (c: string): void => { if (!out.includes(c)) out.push(c); };
  for (const r of rows) {
    const checks = r.checks ?? [];
    if (!checks.length) { add(`the work is what ${r.id} covers ("${r.expectation.trim().replace(/\.$/, "")}")`); continue; }
    for (const b of checks) {
      const globs = bindingGlobs(b);
      if (globs && globs.length) add(`changing files matching ${globs.join(", ")}`);
      else if (b.on.resource === "gov.verb") add(`running \`gov ${b.on.event}\``);
      else add(`a ${b.on.event} on ${b.on.resource}`);
    }
  }
  return out;
}

const lead = (rows: readonly RuleRow[]): string => {
  const c02 = rows.some((r) => r.level === "C02"), c03 = rows.some((r) => r.level === "C03");
  return c02 && c03 ? "Required and preferred practice" : c02 ? "Required practice" : "Preferred practice";
};

const cap = (s: string, n: number): string => (s.length <= n ? s : `${s.slice(0, n - 1).replace(/\s+\S*$/, "")}…`);

function renderOne(doc: string, section: string, rows: readonly RuleRow[], heading: string | null, name: string): Skill {
  const title = titleOf(heading);
  const base = path.posix.basename(doc);
  const where = `${base} §${section}`;
  const description = cap(
    `${lead(rows)}: ${title ?? `§${section}`} (${where}). Use when ${useWhen(rows).join("; or ")}.`,
    SKILL_DESCRIPTION_MAX,
  );
  const version = rows.map((r) => r.start.version).reduce((a, b) => (compareVersions(a, b) >= 0 ? a : b));
  const link = heading ? `${doc}#${anchor(heading)}` : doc;
  const content = [
    "---",
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    `gov-ids: [${rows.map((r) => r.id).join(", ")}]`,
    `policy-version: ${JSON.stringify(version)}`,
    "---",
    "",
    SKILL_MARK,
    "",
    `# ${title ?? `Section ${section}`} — ${where}`,
    "",
    "The rules of this section that bind you while this work is in hand. Each line is a rule's GOV id, how strongly",
    "it binds, and what to do; the rule row that id names is the authority.",
    "",
    ...rows.map(ruleLine),
    "",
    `Source: [${where}${title ? ` ${title}` : ""}](${link}) in the governance repository.`,
    "",
    `_${SKILL_GENERATED[0]!.toUpperCase()}${SKILL_GENERATED.slice(1)}: change the rule rows or the policy, then run \`gov rules build\`._`,
    "",
  ].join("\n");
  return { name, doc, section, title, ids: rows.map((r) => r.id), content };
}

/** Every skill, in the order its first rule is read (framework then org, each by id number). */
export function renderSkills(set: RuleSet, readDoc: ReadDoc = () => null): Skill[] {
  const groups = new Map<string, { doc: string; section: string; rows: RuleRow[] }>();
  for (const r of onDemandRows(set)) {
    const key = `${r.source.doc}\u0000${r.source.section}`;
    const g = groups.get(key) ?? { doc: r.source.doc, section: r.source.section, rows: [] };
    g.rows.push(r);
    groups.set(key, g);
  }
  const texts = new Map<string, string | null>();
  const text = (doc: string): string | null => {
    if (!texts.has(doc)) texts.set(doc, readDoc(doc));
    return texts.get(doc)!;
  };
  const used = new Set<string>();
  const out: Skill[] = [];
  for (const g of groups.values()) {
    const heading = headingOf(text(g.doc), g.section);
    const first = nameOf(g.doc, g.section, titleOf(heading));
    let name = first;
    // Two documents with one base name, same section and title: keep both, distinguishably and stably.
    for (let n = 2; used.has(name); n++) name = `${first.slice(0, SKILL_NAME_MAX - String(n).length - 1).replace(/-+$/, "")}-${n}`;
    used.add(name);
    out.push(renderOne(g.doc, g.section, g.rows, heading, name));
  }
  return out;
}

/** Each skill at each verified location, relative to the directory the agent runs in (POSIX). */
export function skillFiles(skills: readonly Skill[]): { readonly path: string; readonly content: string }[] {
  return SKILL_TARGETS.flatMap((t) => skills.map((s) => ({ path: `${t.dir}/${s.name}/SKILL.md`, content: s.content })));
}
