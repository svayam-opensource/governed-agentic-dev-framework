/**
 * LIFECYCLE STEP SKILLS (intent 03 spec §5, D6; ruling Q13; task L15).
 *
 * Rule rows say what binds an agent; the lifecycle says how the organization writes its artifacts. An agent asked
 * to draft a spec — a person's agent or autorun's — should write it the org's way without being told where to look.
 * So each active step that produces an artifact an agent drafts before or during build gets a skill:
 *
 *   UNIT     one per step of `policies/active/ai-sdlc-lifecycle.md` among intent, spec, plan, build — read by
 *            `parseLifecycle` (X7 headings). Deploy and run are operators' artifacts and get none. No active
 *            lifecycle → no lifecycle skills; a step gov cannot parse → no skill for it (doctor already says why).
 *   NAME     `gov-lifecycle-<step>`.
 *   FRONT    `name`, `description` (what + "Use when …"), `source` (the policy), `template` (the step's template).
 *            No `gov-ids`: the lifecycle is the org's prose, not rule rows.
 *   BODY     the step's own section, verbatim; the sections the artifact must carry (§2.3, which gov checks); the
 *            template inline, so the agent needs no second read; a link to the source; "generated by gov — do not
 *            edit".
 *
 * Pure and byte-stable, like the rule skills: documents in, skills out.
 */
import {
  parseLifecycle, sectionBody, ARTIFACT_SECTIONS, LIFECYCLE_POLICY_PATH, type ArtifactKind,
} from "../intent/lifecycle-policy.js";
import { anchor, cap, SKILL_DESCRIPTION_MAX, type ReadDoc, type Skill } from "./render.js";
import { SKILL_GENERATED, SKILL_MARK, SKILL_PREFIX } from "./locations.js";

/** The steps that get a skill, in lifecycle order (Q13). */
export const LIFECYCLE_SKILL_STEPS: readonly ArtifactKind[] = ["intent", "spec", "plan", "build"];

/** Where an artifact of this step is written (Q1: one path, one scanner). */
const artifactPath = (step: ArtifactKind): string => `projects/<PRJ>/intents/<NN-slug>/${step}.md`;

/** A fence longer than any backtick run in the text, so a template holding code blocks stays one block. */
function fenced(text: string, info: string): string {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = "`".repeat(Math.max(4, longest + 1));
  return `${fence}${info}\n${text.replace(/\n+$/, "")}\n${fence}`;
}

const article = (step: ArtifactKind): string => (step === "intent" ? "an" : "a");

/** Every lifecycle step skill — none when `readDoc` finds no active lifecycle. */
export function renderLifecycleSkills(readDoc: ReadDoc): Skill[] {
  const policy = readDoc(LIFECYCLE_POLICY_PATH);
  if (policy === null) return [];
  const { steps } = parseLifecycle(policy);
  const out: Skill[] = [];
  for (const want of LIFECYCLE_SKILL_STEPS) {
    const step = steps.find((s) => s.step === want);
    if (!step) continue;
    const title = step.heading.replace(/\s*\(phase:[^)]*\)\s*$/i, "").trim();
    const name = `${SKILL_PREFIX}lifecycle-${want}`;
    const body = sectionBody(policy, step.heading) ?? "";
    const template = step.template ? readDoc(step.template) : null;
    const file = artifactPath(want);
    const when = `drafting, revising or reviewing ${article(want)} \`${want}.md\` (\`${file}\`)`;
    const description = cap(
      `How this organization writes ${article(want)} ${want}: the ${title} step of its lifecycle (ai-sdlc-lifecycle.md), `
      + `the sections it must carry and its template. Use when ${when}.`,
      SKILL_DESCRIPTION_MAX,
    );
    // The heading as written in the file (number included) is what GitHub anchors; re-read it from the policy.
    const headingLine = policy.split(/\r?\n/).find((l) => l.startsWith("## ") && l.includes(step.heading));
    const link = headingLine ? `${LIFECYCLE_POLICY_PATH}#${anchor(headingLine.replace(/^##\s+/, ""))}` : LIFECYCLE_POLICY_PATH;
    const content = [
      "---",
      `name: ${name}`,
      `description: ${JSON.stringify(description)}`,
      `source: ${LIFECYCLE_POLICY_PATH}`,
      ...(step.template ? [`template: ${step.template}`] : []),
      "---",
      "",
      SKILL_MARK,
      "",
      `# ${title} — writing \`${want}.md\` the organization's way`,
      "",
      `You are writing \`${file}\`. Below is what the organization's lifecycle says about this step, the sections the`,
      "artifact must carry, and its template. The lifecycle policy is the authority; this is a copy of it.",
      "",
      `## What the lifecycle says — ${title}`,
      "",
      body,
      "",
      `## What \`${want}.md\` must carry`,
      "",
      "Open with the template's front matter and the Status line `**Status:** DRAFT`. You never write APPROVED: gov",
      "writes it when a person approves the change request and it merges.",
      "",
      "Then every one of these sections, as a `##` heading, in this order:",
      "",
      ...ARTIFACT_SECTIONS[want].map((h) => `- ${h}`),
      "",
      `## The template — \`${step.template ?? "(none named)"}\``,
      "",
      template !== null
        ? fenced(template, "markdown")
        : `The template${step.template ? ` \`${step.template}\`` : ""} could not be read when this skill was generated; `
          + "write the sections above, in that order.",
      "",
      `Source: [ai-sdlc-lifecycle.md — ${title}](${link}) in the governance repository.`,
      "",
      `_${SKILL_GENERATED[0]!.toUpperCase()}${SKILL_GENERATED.slice(1)}: change the lifecycle policy or its template, then run \`gov rules build\`._`,
      "",
    ].join("\n");
    out.push({ name, doc: LIFECYCLE_POLICY_PATH, section: want, title, ids: [], content, when });
  }
  return out;
}
