/**
 * THE FALLBACK SKILL INDEX (intent 03 spec §5, D6; ruling Q14; task L15).
 *
 * A skill reaches an agent two ways. An agent whose catalog entry has a `skillsDir` — a location gov has SEEN it
 * load skills from — gets them there natively. Every other agent gets them through its harness file: an index
 * section, rendered with the harness by the same code, that says "when a task matches X, read <path>", the path
 * being the fallback copy under `.agents/skills/`. An agent that can read a file can follow that, so no agent is
 * left without its skills because nobody has verified its loader yet.
 *
 * A harness file carries the index when ANY agent reading it lacks a verified location (AGENTS.md serves codex and
 * Bob alike). It goes AFTER the protocol, so the protocol and its resident block are byte-for-byte what they were;
 * with no skills there is no section at all.
 */
import { AGENT_CATALOG, harnessFileFor } from "../cli/agent-catalog.js";
import { FALLBACK_SKILLS_DIR } from "./locations.js";
import type { Skill } from "./render.js";

export const SKILL_INDEX_HEADING = "## Skills — read the one your task needs";
/** Marks the section as gov's, so nobody edits the copy. */
export const SKILL_INDEX_MARK = "<!-- gov skill index (Q14): generated by gov from the skills it renders — do not edit -->";

/** Does this harness file (a `HARNESS_TARGETS` path) need the index? Yes unless every agent reading it loads skills natively. */
export function needsSkillIndex(harnessPath: string): boolean {
  const readers = AGENT_CATALOG.filter((a) => harnessFileFor(a.id) === harnessPath);
  return readers.length === 0 || readers.some((a) => !a.skillsDir);
}

/** The index section, or "" when there are no skills. */
export function renderSkillIndex(skills: readonly Skill[]): string {
  if (!skills.length) return "";
  return [
    SKILL_INDEX_HEADING,
    "",
    SKILL_INDEX_MARK,
    "",
    "Your agent has no skill loader gov has seen work, so your skills are listed here. Before you start a task that",
    "matches a line below, read the file it names and follow it: it holds the rules and the way of working that bind",
    "that work. Read only the ones your task needs.",
    "",
    ...skills.map((s) => `- When ${s.when}: read \`${FALLBACK_SKILLS_DIR}/${s.name}/SKILL.md\`${s.title ? ` (${s.title})` : ""}.`),
    "",
  ].join("\n");
}

/** The harness file with the index after it; unchanged when the index is empty. */
export function withSkillIndex(content: string, index: string): string {
  if (!index) return content;
  return `${content.replace(/\n+$/, "")}\n\n${index.replace(/\n+$/, "")}\n`;
}
