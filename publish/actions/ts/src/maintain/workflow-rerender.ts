/**
 * THE UPGRADE RE-RENDERS THE GOV REPO'S INSTALLED WORKFLOWS (PRJ-121 intent 01, task B07; Policy Owner ruling Q9).
 *
 * Two workflows in the governance repo's `.github/workflows/` are gov's, not the org's:
 *
 *   approver-check.yml   copied from the framework's template by `gov repo protect apply`
 *   gov-checks.yml       rendered from the rule stores by `gov check install`
 *
 * When an upgrade changes what either would be, the upgrade refreshes the installed copy itself — in the same pull
 * request (`--pr`) or the same working tree (`--apply`). The alternative, a post-merge `gov repo protect apply`, leaves
 * the check red (reading a role list at its old path) until somebody remembers to run it.
 *
 * PINNED TO THE GOV THAT WROTE IT. The re-rendered gov-checks.yml installs `@svayam-opensource/gov@<this gov>`, not
 * whatever npm calls `latest` — during a pre-release line `latest` is the previous major, which does not know the
 * layout the upgrade brings, and the upgrade PR's own CI would run it.
 *
 * NEVER OVER A PERSON'S EDIT. Each copy is re-rendered only when it is provably gov's own bytes:
 *   approver-check.yml   equal to the template the workspace held BEFORE this upgrade
 *   gov-checks.yml       its digest line still holds (render-github `digestHolds`); a copy from a gov older than the
 *                        digest counts as gov's while it carries the GENERATED banner — the rule `gov check install
 *                        --all` has always applied
 * Anything else is a conflict: listed, never overwritten. "Unchanged" (the template did not change, the render did not
 * change) is untouched, byte for byte — the pin is not bumped on its own.
 *
 * Permanent code (not bridge): every upgrade that changes a template runs it.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { WORKFLOW_DEST } from "./repo-protect.js";
import { WORKFLOW_PATH as GOV_CHECKS_PATH, digestHolds, pinnedGovPackage } from "../rules/checks/render-github.js";
import { log } from "../log.js";

/** Where `gov repo protect apply` installs the approver check in a repository. */
export const APPROVER_CHECK_INSTALLED = WORKFLOW_DEST;
/** The banner every gov-checks.yml gov ever rendered starts with (check-scope GENERATED_MARK). */
const GENERATED_MARK = "# GENERATED by gov from the rule stores";
/** The published gov, as the re-rendered gov-checks.yml installs it — always with a version. */
export const GOV_PACKAGE_NAME = "@svayam-opensource/gov";

export type RerenderState = "rerendered" | "unchanged" | "conflict" | "absent" | "cannot-tell";
export interface RerenderOutcome { readonly path: string; readonly state: RerenderState; readonly detail: string }

export interface RerenderInput {
  readonly adopterDir: string;
  /** The approver-check template as this workspace held it BEFORE the upgrade; null when it held none. */
  readonly oldApproverTemplate: string | null;
  /** The approver-check template the new content ships; null when it ships none. */
  readonly newApproverTemplate: string | null;
  /** The gov running the upgrade: the version the re-rendered gov-checks.yml installs. */
  readonly govVersion: string;
  /** Override what the re-rendered gov-checks.yml installs (`gov upgrade --gov-package`). Default: the pinned gov. */
  readonly govPackage?: string;
  /**
   * gov-checks.yml as `gov check install` would render it for this gov repo NOW, installing `govPackage`; null when the
   * rules cannot be read or nothing binds. Injected (cli wires the rule stores) — absent → gov-checks is not looked at.
   */
  readonly renderGovChecks?: (govPackage: string) => string | null;
  /** false: say what would happen, write nothing. */
  readonly apply: boolean;
}

const readIf = (p: string): string | null => (fs.existsSync(p) && fs.statSync(p).isFile() ? fs.readFileSync(p, "utf8") : null);

function approverCheck(input: RerenderInput): RerenderOutcome {
  const at = APPROVER_CHECK_INSTALLED;
  const installed = readIf(path.join(input.adopterDir, at));
  const { oldApproverTemplate: before, newApproverTemplate: after } = input;
  if (installed === null) return { path: at, state: "absent", detail: "not installed — `gov repo protect apply` installs it" };
  if (after === null || installed === after) return { path: at, state: "unchanged", detail: "already the template this content ships" };
  if (before !== null && installed === before) {
    return before === after
      ? { path: at, state: "unchanged", detail: "the template did not change" }
      : { path: at, state: "rerendered", detail: "the framework's template changed — refreshed from it" };
  }
  return {
    path: at, state: "conflict",
    detail: before === null
      ? "differs from the new template, and this workspace held no template to tell an edit from an older copy — left as it is; compare it with the template and reconcile by hand"
      : "differs from the template it was installed from (edited by hand) — left as it is; reconcile it with the new template by hand",
  };
}

function govChecks(input: RerenderInput): RerenderOutcome | null {
  if (!input.renderGovChecks) return null;
  const at = GOV_CHECKS_PATH;
  const installed = readIf(path.join(input.adopterDir, at));
  if (installed === null) return { path: at, state: "absent", detail: "not installed — `gov check install` writes it" };
  if (!installed.startsWith(GENERATED_MARK)) return { path: at, state: "conflict", detail: "not written by gov (no GENERATED banner) — left as it is" };
  if (digestHolds(installed) === false) return { path: at, state: "conflict", detail: "edited by hand (its digest line no longer matches) — left as it is; re-run `gov check install` once the edit is moved into the rules" };
  // Unchanged: what gov renders today, installing what this copy installs, is this copy.
  const own = pinnedGovPackage(installed) ?? GOV_PACKAGE_NAME;
  const same = input.renderGovChecks(own);
  if (same === null) return { path: at, state: "cannot-tell", detail: "the rules could not be rendered here — left as it is; run `gov check install` after the upgrade" };
  if (same === installed) return { path: at, state: "unchanged", detail: "the render did not change" };
  const pkg = input.govPackage ?? `${GOV_PACKAGE_NAME}@${input.govVersion}`;
  const want = input.renderGovChecks(pkg);
  if (want === null) return { path: at, state: "cannot-tell", detail: "the rules could not be rendered here — left as it is; run `gov check install` after the upgrade" };
  return { path: at, state: "rerendered", detail: `the render changed — re-rendered, installing ${pkg}` };
}

/**
 * Re-render the installed workflows an upgrade changed (Q9). With `apply`, writes the re-rendered ones; either way returns
 * one outcome per workflow and the summary lines (nothing for an untouched or absent one).
 */
export function rerenderInstalledWorkflows(input: RerenderInput): { outcomes: RerenderOutcome[]; lines: string[] } {
  const outcomes = [approverCheck(input), govChecks(input)].filter((o): o is RerenderOutcome => o !== null);
  const lines: string[] = [];
  for (const o of outcomes) {
    if (o.state === "rerendered") {
      if (input.apply) {
        const text = o.path === APPROVER_CHECK_INSTALLED ? input.newApproverTemplate! : input.renderGovChecks!(input.govPackage ?? `${GOV_PACKAGE_NAME}@${input.govVersion}`)!;
        fs.writeFileSync(path.join(input.adopterDir, o.path), text, "utf8");
        log("info", "re-rendered an installed workflow", "gov-work:maintain:workflow-rerender", "rerenderInstalledWorkflows", { path: o.path });
        lines.push(`  ${o.path}: ${o.detail}`);
      } else {
        lines.push(`  ~ update   ${o.path}   (${o.detail})`);
      }
    } else if (o.state === "conflict" || o.state === "cannot-tell") {
      lines.push(`  ! ${o.path}: ${o.detail}`);
    }
  }
  return { outcomes, lines };
}
