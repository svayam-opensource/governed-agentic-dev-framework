/**
 * `gov check install --all` AND `gov check status` — the check workflow across a project's repositories
 * (rule-model-design.md Q14: a binding is rendered into each resource's own automation; P3 wave 3).
 *
 * SCOPE. The governance repository's working tree, and every CODE repository linked to the project — the board's
 * repositories (GitHub is the source of truth), at their clones `<agent_work_root>/<PROJECT_ID>/<repo>/`. The
 * project is the one the governance repo's branch names, or `--project <id>`.
 *
 * install --all WRITES ONLY ON A PROJECT OR TASK BRANCH of that project. A repository on its default branch (or any
 * other) is refused and the reason printed: gov never writes a default branch. It never commits or pushes; it ends
 * with the commands the person runs. Identical bytes are reported `unchanged` and not rewritten. A repository no rule
 * binds gets nothing; a workflow gov wrote there earlier is reported, and removed only with `--prune`.
 *
 * status compares each repository's installed workflow with what install would write now: in-sync, stale, missing,
 * or cannot-tell (not cloned, not a git working tree, the board unreadable) — never in-sync on a guess.
 *
 * Pure over injected readers and writers; main.ts wires them.
 */
