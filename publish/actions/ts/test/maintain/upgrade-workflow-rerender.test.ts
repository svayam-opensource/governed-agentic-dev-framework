/**
 * THE UPGRADE RE-RENDERS THE GOV REPO'S INSTALLED WORKFLOWS (PRJ-121 intent 01, task B07, Policy Owner ruling Q9).
 *
 * `approver-check.yml` (copied by `gov repo protect apply`) and `gov-checks.yml` (rendered by `gov check install`) sit in
 * the gov repo's `.github/workflows/`. When an upgrade changes what they would be, the upgrade itself refreshes them —
 * a post-merge `gov repo protect apply` leaves the check red until somebody runs it. The re-rendered `gov-checks.yml`
 * installs the gov that wrote it (pinned), so the upgrade PR's own CI runs a gov that knows the layout it brings.
 *
 *   template changed  → re-rendered (gov-checks pinned to this gov)
 *   unchanged         → untouched, byte for byte
 *   edited by hand    → a conflict, listed, never overwritten
 *
 * X13 (intent 02, 2026-10-12): every gov-checks job carries `id-token: write`, licensed org or not — one render, no flap.
 */
import { expect } from "chai";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { execFileSync } from "node:child_process";
import { rerenderInstalledWorkflows, APPROVER_CHECK_INSTALLED } from "../../src/maintain/workflow-rerender.js";
import { runUpgradeSync, runUpgradePr } from "../../src/maintain/upgrade-run.js";
import { renderWorkflow, WORKFLOW_PATH, digestHolds, pinnedGovPackage } from "../../src/rules/checks/render-github.js";
import { WORKFLOW_TEMPLATE } from "../../src/maintain/repo-protect.js";
import type { CheckBinding } from "../../src/rules/model/catalog.js";
import { withInstalledPin, type CheckVerbConfig } from "../../src/cli/check-verb.js";

const TEMPLATE_POSIX = WORKFLOW_TEMPLATE.split(path.sep).join("/");
const tmp = (p: string): string => fs.mkdtempSync(path.join(os.tmpdir(), p));
const put = (root: string, rel: string, text: string): void => { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), text); };
const read = (root: string, rel: string): string | null => { try { return fs.readFileSync(path.join(root, rel), "utf8"); } catch { return null; /* absent */ } };

const OLD_TEMPLATE = "name: approver-check\n# reads policies/authorized-representatives.md\n";
const NEW_TEMPLATE = "name: approver-check\n# reads policies/common/authorized-representatives.md\n";
const HAND_EDITED = "name: approver-check\n# reads policies/authorized-representatives.md\n# our own extra step\n";

const binding = (id: string, resource = "vcs.gov-repo", event = "pull_request"): { id: string; check: CheckBinding } =>
  ({ id, check: { on: { resource, event }, action: "gov-builtin/frontmatter-required", on_miss: "fail" } });
const BINDINGS = [binding("GOV-FRM-061")];
/** What `gov check install` renders for the gov repo with these bindings, installing `pkg`. */
const render = (pkg?: string, bindings = BINDINGS): string => renderWorkflow(bindings, pkg ? { govPackage: pkg } : {})[0]!.text;

describe("gov-checks render: X13 id-token, a digest, a pin (B07)", () => {
  it("every job carries `id-token: write` — licensed or not, one render (X13)", () => {
    const text = render(undefined, [binding("GOV-FRM-061"), binding("GOV-FRM-062", "vcs.gov-repo", "push")]);
    const jobs = (text.match(/^ {4}runs-on: /gm) ?? []).length;
    expect(jobs).to.equal(2);
    expect((text.match(/^ {6}id-token: write$/gm) ?? []).length).to.equal(jobs);
    expect(text).to.not.match(/^ {2}id-token/m); // per job, never only at the top (a job's own permissions replace it)
  });

  it("the last line is a digest of the lines above it; an edit breaks it", () => {
    const text = render();
    expect(text.trimEnd().split("\n").pop()).to.match(/^# gov digest sha256:[0-9a-f]{64}\b/);
    expect(digestHolds(text)).to.equal(true);
    expect(digestHolds(text.replace("timeout-minutes: 10", "timeout-minutes: 30"))).to.equal(false);
    expect(digestHolds("# GENERATED by gov from the rule stores — do not edit\nname: gov-checks\n")).to.equal(null);
  });

  it("the npm install line's package is read back: pinned or not", () => {
    expect(pinnedGovPackage(render("@svayam-opensource/gov@2.0.0"))).to.equal("@svayam-opensource/gov@2.0.0");
    expect(pinnedGovPackage(render())).to.equal(null);
  });
});

describe("gov check install / status keep the pin an installed copy carries (Q9)", () => {
  const cfg: CheckVerbConfig = { home: "/gov", defaultBranch: "main", defaultCodeBranch: "main", githubOrg: "acme", workspaceRepo: "acme-gov", posture: "soft" };
  it("a pinned copy → its pin; an unpinned or absent copy → the default; --gov-package wins", () => {
    expect(withInstalledPin(cfg, render("@svayam-opensource/gov@2.0.0")).govPackage).to.equal("@svayam-opensource/gov@2.0.0");
    expect(withInstalledPin(cfg, render()).govPackage).to.equal(undefined);
    expect(withInstalledPin(cfg, null).govPackage).to.equal(undefined);
    expect(withInstalledPin({ ...cfg, govPackage: "./gov.tgz" }, render("@svayam-opensource/gov@2.0.0")).govPackage).to.equal("./gov.tgz");
  });
});

describe("the upgrade re-renders the installed workflows (Q9)", () => {
  const ws = (): string => tmp("rerender-ws-");

  describe("approver-check.yml", () => {
    it("template changed, installed copy is the old template → re-rendered from the new one", () => {
      const dir = ws();
      put(dir, APPROVER_CHECK_INSTALLED, OLD_TEMPLATE);
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: OLD_TEMPLATE, newApproverTemplate: NEW_TEMPLATE, govVersion: "2.0.0", apply: true });
      expect(read(dir, APPROVER_CHECK_INSTALLED)).to.equal(NEW_TEMPLATE);
      expect(r.outcomes.find((o) => o.path === APPROVER_CHECK_INSTALLED)!.state).to.equal("rerendered");
      expect(r.lines.join("\n")).to.include(APPROVER_CHECK_INSTALLED);
    });

    it("template unchanged → untouched", () => {
      const dir = ws();
      put(dir, APPROVER_CHECK_INSTALLED, OLD_TEMPLATE);
      const before = fs.statSync(path.join(dir, APPROVER_CHECK_INSTALLED)).mtimeMs;
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: OLD_TEMPLATE, newApproverTemplate: OLD_TEMPLATE, govVersion: "2.0.0", apply: true });
      expect(read(dir, APPROVER_CHECK_INSTALLED)).to.equal(OLD_TEMPLATE);
      expect(fs.statSync(path.join(dir, APPROVER_CHECK_INSTALLED)).mtimeMs).to.equal(before);
      expect(r.outcomes.find((o) => o.path === APPROVER_CHECK_INSTALLED)!.state).to.equal("unchanged");
      expect(r.lines).to.deep.equal([]);
    });

    it("an installed copy edited by hand → a conflict, listed, never overwritten", () => {
      const dir = ws();
      put(dir, APPROVER_CHECK_INSTALLED, HAND_EDITED);
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: OLD_TEMPLATE, newApproverTemplate: NEW_TEMPLATE, govVersion: "2.0.0", apply: true });
      expect(read(dir, APPROVER_CHECK_INSTALLED)).to.equal(HAND_EDITED);
      expect(r.outcomes.find((o) => o.path === APPROVER_CHECK_INSTALLED)!.state).to.equal("conflict");
      expect(r.lines.join("\n")).to.match(/approver-check\.yml.*(edited|differs)/);
    });

    it("not installed → nothing written (gov repo protect apply installs it)", () => {
      const dir = ws();
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: OLD_TEMPLATE, newApproverTemplate: NEW_TEMPLATE, govVersion: "2.0.0", apply: true });
      expect(read(dir, APPROVER_CHECK_INSTALLED)).to.equal(null);
      expect(r.outcomes.find((o) => o.path === APPROVER_CHECK_INSTALLED)!.state).to.equal("absent");
    });

    it("a dry run says what it would re-render and writes nothing", () => {
      const dir = ws();
      put(dir, APPROVER_CHECK_INSTALLED, OLD_TEMPLATE);
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: OLD_TEMPLATE, newApproverTemplate: NEW_TEMPLATE, govVersion: "2.0.0", apply: false });
      expect(read(dir, APPROVER_CHECK_INSTALLED)).to.equal(OLD_TEMPLATE);
      expect(r.lines.join("\n")).to.include(APPROVER_CHECK_INSTALLED);
    });
  });

  describe("gov-checks.yml", () => {
    it("the render changed → re-rendered, pinned to the gov that wrote it", () => {
      const dir = ws();
      // Written by an earlier gov from fewer bindings: the render today differs.
      put(dir, WORKFLOW_PATH, render(undefined, [binding("GOV-FRM-060")]));
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: null, newApproverTemplate: null, govVersion: "2.0.0", renderGovChecks: (pkg) => render(pkg), apply: true });
      const now = read(dir, WORKFLOW_PATH)!;
      expect(now).to.equal(render("@svayam-opensource/gov@2.0.0"));
      expect(now).to.include("npm install -g @svayam-opensource/gov@2.0.0");
      expect(r.outcomes.find((o) => o.path === WORKFLOW_PATH)!.state).to.equal("rerendered");
    });

    it("unchanged → untouched (the render with the copy's own package is the copy)", () => {
      const dir = ws();
      const installed = render("@svayam-opensource/gov@1.9.0");
      put(dir, WORKFLOW_PATH, installed);
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: null, newApproverTemplate: null, govVersion: "2.0.0", renderGovChecks: (pkg) => render(pkg), apply: true });
      expect(read(dir, WORKFLOW_PATH)).to.equal(installed);
      expect(r.outcomes.find((o) => o.path === WORKFLOW_PATH)!.state).to.equal("unchanged");
    });

    it("a copy edited by hand (its digest no longer holds) → a conflict, never overwritten", () => {
      const dir = ws();
      const edited = render(undefined, [binding("GOV-FRM-060")]).replace("timeout-minutes: 10", "timeout-minutes: 30");
      put(dir, WORKFLOW_PATH, edited);
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: null, newApproverTemplate: null, govVersion: "2.0.0", renderGovChecks: (pkg) => render(pkg), apply: true });
      expect(read(dir, WORKFLOW_PATH)).to.equal(edited);
      expect(r.outcomes.find((o) => o.path === WORKFLOW_PATH)!.state).to.equal("conflict");
    });

    it("a workflow gov did not write (no GENERATED banner) → a conflict, never overwritten", () => {
      const dir = ws();
      put(dir, WORKFLOW_PATH, "name: gov-checks\non: push\n");
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: null, newApproverTemplate: null, govVersion: "2.0.0", renderGovChecks: (pkg) => render(pkg), apply: true });
      expect(read(dir, WORKFLOW_PATH)).to.equal("name: gov-checks\non: push\n");
      expect(r.outcomes.find((o) => o.path === WORKFLOW_PATH)!.state).to.equal("conflict");
    });

    it("the rules cannot be rendered → left alone, and said", () => {
      const dir = ws();
      const installed = render(undefined, [binding("GOV-FRM-060")]);
      put(dir, WORKFLOW_PATH, installed);
      const r = rerenderInstalledWorkflows({ adopterDir: dir, oldApproverTemplate: null, newApproverTemplate: null, govVersion: "2.0.0", renderGovChecks: () => null, apply: true });
      expect(read(dir, WORKFLOW_PATH)).to.equal(installed);
      expect(r.outcomes.find((o) => o.path === WORKFLOW_PATH)!.state).to.equal("cannot-tell");
    });
  });
});

describe("gov upgrade carries the re-render (Q9)", function () {
  this.timeout(30000);

  function content(template: string): string {
    const c = tmp("rerender-content-");
    put(c, "MANIFEST.yaml", [
      "files:",
      "  - { src: VERSION, dst: VERSION, mode: scaffold-auto }",
      // A MANIFEST names paths with `/`, as the real one does; WORKFLOW_TEMPLATE is an OS path (`\` on Windows).
      `  - { src: ${TEMPLATE_POSIX}, dst: ${TEMPLATE_POSIX}, mode: scaffold-auto }`,
      "",
    ].join("\n"));
    put(c, "VERSION", "2.0.0\n");
    put(c, WORKFLOW_TEMPLATE, template);
    return c;
  }
  function workspace(): string {
    const w = tmp("rerender-up-ws-");
    put(w, "org-config.yaml", 'org_name: "Acme Corp"\ngithub_org: "acme"\n');
    put(w, "VERSION", "1.9.0\n");
    put(w, WORKFLOW_TEMPLATE, OLD_TEMPLATE);
    put(w, APPROVER_CHECK_INSTALLED, OLD_TEMPLATE);
    return w;
  }

  it("--apply: the template changed → the installed approver-check is the new template", () => {
    const w = workspace();
    const r = runUpgradeSync(content(NEW_TEMPLATE), w, { apply: true, govVersion: "2.0.0" });
    expect(r.code, r.lines.join("\n")).to.equal(0);
    expect(read(w, APPROVER_CHECK_INSTALLED)).to.equal(NEW_TEMPLATE);
    expect(r.lines.join("\n")).to.include(APPROVER_CHECK_INSTALLED);
  });

  it("--apply: a hand-edited installed copy is kept, and the summary names the conflict", () => {
    const w = workspace();
    put(w, APPROVER_CHECK_INSTALLED, HAND_EDITED);
    const r = runUpgradeSync(content(NEW_TEMPLATE), w, { apply: true, govVersion: "2.0.0" });
    expect(read(w, APPROVER_CHECK_INSTALLED)).to.equal(HAND_EDITED);
    expect(r.lines.join("\n")).to.match(/approver-check\.yml.*(edited|differs)/);
  });

  it("dry run: lists the re-render, writes nothing", () => {
    const w = workspace();
    const r = runUpgradeSync(content(NEW_TEMPLATE), w, { apply: false });
    expect(read(w, APPROVER_CHECK_INSTALLED)).to.equal(OLD_TEMPLATE);
    expect(r.lines.join("\n")).to.include(APPROVER_CHECK_INSTALLED);
  });

  it("--pr: the re-rendered workflows are on the upgrade branch, gov-checks pinned", () => {
    const w = workspace();
    put(w, WORKFLOW_PATH, render(undefined, [binding("GOV-FRM-060")]));
    const remote = tmp("rerender-remote-");
    execFileSync("git", ["init", "-q", "--bare", remote]);
    const g = (...a: string[]): string => execFileSync("git", ["-C", w, ...a], { encoding: "utf8" });
    g("init", "-q", "-b", "main"); g("config", "user.email", "t@example.com"); g("config", "user.name", "t");
    g("remote", "add", "origin", remote);
    g("add", "-A"); g("commit", "-qm", "seed");
    const r = runUpgradePr(content(NEW_TEMPLATE), w, { userHome: tmp("rerender-home-"), openPr: () => "https://example.test/pr/1", govVersion: "2.0.0", renderGovChecks: (pkg) => render(pkg) });
    expect(r.code, r.lines.join("\n")).to.equal(0);
    expect(g("show", `gov-upgrade-2.0.0:${APPROVER_CHECK_INSTALLED}`)).to.equal(NEW_TEMPLATE);
    expect(g("show", `gov-upgrade-2.0.0:${WORKFLOW_PATH}`)).to.equal(render("@svayam-opensource/gov@2.0.0"));
    // The clone went home; its own copies are as they were (EOL-blind: Git for Windows checks text out with CRLF).
    expect(read(w, APPROVER_CHECK_INSTALLED)?.replace(/\r\n/g, "\n")).to.equal(OLD_TEMPLATE);
  });
});
