/**
 * THE FILE LIST, generated from the staged tree (no `heat`, no WiX-version-specific harvesting).
 *
 * A per-user package installs into the user's profile, where Windows Installer wants each component's key path
 * to be an HKCU registry value rather than a file (ICE38) and each created directory to be removed on uninstall
 * (ICE64). So: one component per directory, holding that directory's files, keyed by a value under
 * HKCU\Software\Svayam\gov\Components, with a RemoveFolder. GUIDs are derived from the relative path, so the same
 * tree always yields the same source. Only bin\ carries the PATH entry, in the user's environment (System="no").
 */
import { createHash } from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";

const TOP = { node: "NODEFOLDER", app: "APPFOLDER", bin: "BINFOLDER" };
export const REG_KEY = "Software\\Svayam\\gov\\Components";

const h = (s) => createHash("sha1").update(`gov-msi:${s}`).digest("hex");
/** A name-based GUID (RFC 4122 v5 layout) for a relative path. */
export function stableGuid(rel) {
  const x = h(`guid:${rel}`);
  const v = ((parseInt(x[16], 16) & 0x3) | 0x8).toString(16);
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-5${x.slice(13, 16)}-${v}${x.slice(17, 20)}-${x.slice(20, 32)}`.toUpperCase();
}
const id = (prefix, rel) => `${prefix}${h(rel).slice(0, 24)}`;
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** The components fragment for the staged tree at `root` (which holds node\, app\, bin\). */
export function componentsWxs(root) {
  const comps = [];
  const lines = [];
  const walk = (abs, rel, dirId, name, depth) => {
    const pad = "  ".repeat(depth);
    lines.push(`${pad}<Directory Id="${dirId}" Name="${esc(name)}">`);
    const entries = fs.readdirSync(abs, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    const files = entries.filter((e) => e.isFile());
    const dirs = entries.filter((e) => e.isDirectory());
    const cid = id("c", rel);
    comps.push(cid);
    lines.push(`${pad}  <Component Id="${cid}" Guid="${stableGuid(rel)}">`);
    lines.push(`${pad}    <RegistryValue Root="HKCU" Key="${REG_KEY}" Name="${cid}" Type="integer" Value="1" KeyPath="yes" />`);
    lines.push(`${pad}    <RemoveFolder Id="${id("r", rel)}" On="uninstall" />`);
    if (files.length === 0) lines.push(`${pad}    <CreateFolder />`);
    for (const f of files) {
      lines.push(`${pad}    <File Id="${id("f", `${rel}/${f.name}`)}" Name="${esc(f.name)}" Source="${esc(path.join(abs, f.name))}" />`);
    }
    if (dirId === TOP.bin) {
      // THE ONLY PATH ENTRY: bin\, appended to the user's PATH, removed on uninstall. node\ never goes on PATH (#211).
      lines.push(`${pad}    <Environment Id="GovUserPath" Name="PATH" Value="[BINFOLDER]" Part="last" Action="set" System="no" Permanent="no" />`);
    }
    lines.push(`${pad}  </Component>`);
    for (const d of dirs) walk(path.join(abs, d.name), `${rel}/${d.name}`, id("d", `${rel}/${d.name}`), d.name, depth + 1);
    lines.push(`${pad}</Directory>`);
  };
  for (const [name, dirId] of Object.entries(TOP)) {
    const abs = path.join(root, name);
    if (!fs.existsSync(abs)) throw new Error(`staged tree has no ${name}\\ (${abs})`);
    walk(abs, name, dirId, name, 3);
  }
  return [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- GENERATED by packages/msi/lib/wxs.mjs from the staged tree. Do not edit. -->`,
    `<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">`,
    `  <Fragment>`,
    `    <DirectoryRef Id="INSTALLFOLDER">`,
    ...lines,
    `    </DirectoryRef>`,
    `    <ComponentGroup Id="GovFiles">`,
    ...comps.map((c) => `      <ComponentRef Id="${c}" />`),
    `    </ComponentGroup>`,
    `  </Fragment>`,
    `</Wix>`,
    ``,
  ].join("\n");
}
